import { AppError } from './AppError';

export class AuthError extends AppError {
  constructor(message: string = 'Autentikasi gagal') {
    super(message, 401);
    this.name = 'AuthError';
    Object.setPrototypeOf(this, AuthError.prototype);
  }
}